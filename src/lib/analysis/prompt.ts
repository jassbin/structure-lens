/** 阶段三：对某一条判断继续深挖 / 质疑 / 反驳 */
export type DrillMode = "challenge" | "deeper" | "counter";

export function drillSystemPrompt(mode: DrillMode): string {
  const task =
    mode === "challenge"
      ? "用户在质疑这条判断的依据。请诚实回答：支撑这条判断的依据到底够不够？有哪些是事实、哪些只是推断、哪些是你无法证实的？不要为了显得完整而编造依据。"
      : mode === "counter"
        ? "请为这条判断构造一个真正有力的反面解释：如果它其实是错的，最可能的另一种解释是什么？给出完整的对立论证，而不是几个‘也有可能’。"
        : "请把这条判断再往底层剥一层：它背后更普遍的激励/权力/信息结构是什么？剥到人性与社会的最底层，并说明它能否跨领域迁移。";
  return `你是「结构透镜」的深挖引擎。下面给你一次分析的核心结论、某一层的标题，以及用户点中的那一条判断。

任务：${task}

## 硬约束
- 克制、诚实。无法证实的就说无法证实。
- 直接给结论性的短段落（150 字以内），不要客套、不要重复原话。
- 用中文。只输出这段文字本身，不要 JSON、不要标题。`;
}

/** 从模型回复文本中稳健地抽取 JSON，并对常见 LLM 格式小瑕疵做轻量修复 */
export function extractJson(text: string): unknown {
  const trimmed = text.trim();
  const fenced = trimmed.match(/```(?:json)?\s*([\s\S]*?)```/);
  const candidate = fenced ? fenced[1] : trimmed;
  const start = candidate.indexOf("{");
  const end = candidate.lastIndexOf("}");
  if (start === -1 || end === -1 || end <= start) {
    throw new Error("AI 未返回可解析的结果");
  }
  const raw = candidate.slice(start, end + 1);
  try {
    return JSON.parse(raw);
  } catch {
    // LLM 常见格式毛病（数组元素缺逗号、尾随逗号、单引号等）用 jsonrepair 兜底
    return JSON.parse(jsonrepair(raw));
  }
}
